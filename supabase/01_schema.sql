-- HR Task Tracker: tables (no login)
-- Run this whole file in Supabase > SQL Editor. Safe to run again.
--
-- Access: there is no login. Anyone who has the website link can view, add, edit and
-- delete tasks and lists. They cannot reach anything else in this Supabase project.

begin;

-- ---------- clean up the earlier login version, if it was ever run ----------
drop trigger if exists hr_tasks_new_user on auth.users;
drop function if exists public.rename_list_item(bigint, text);

-- ---------- tables ----------
create table if not exists public.list_items (
  id   bigint generated by default as identity primary key,
  kind text not null check (kind in ('members', 'assigners', 'functions')),
  name text not null check (name = btrim(name) and name <> '' and char_length(name) <= 120)
);
create unique index if not exists list_items_kind_name_key
  on public.list_items (kind, lower(name));

create table if not exists public.app_settings (
  id          int primary key default 1 check (id = 1),
  report_date date
);
insert into public.app_settings (id) values (1) on conflict do nothing;

create table if not exists public.tasks (
  id              text primary key default gen_random_uuid()::text check (char_length(id) between 1 and 64),
  seq             bigint generated by default as identity,   -- keeps the SL. order
  task            text not null check (btrim(task) <> '' and char_length(task) <= 2000),
  assigned_date   date,
  assigned_by     text not null default '' check (char_length(assigned_by) <= 120),
  job_function    text not null default '' check (char_length(job_function) <= 120),
  due_date        date,
  completion_date date,
  assigned_to_1   text not null default '' check (char_length(assigned_to_1) <= 120),
  assigned_to_2   text not null default '' check (char_length(assigned_to_2) <= 120),
  assigned_to_3   text not null default '' check (char_length(assigned_to_3) <= 120),
  priority        text not null default '' check (priority in ('', 'Urgent', 'High', 'Medium', 'Low')),
  pct             int  not null default 0 check (pct between 0 and 100),
  remarks         text not null default '' check (char_length(remarks) <= 2000),
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index if not exists tasks_seq_idx on public.tasks (seq, id);

-- stamps updated_at
drop trigger if exists tasks_guard on public.tasks;
create or replace function public.tasks_touch() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.updated_at := clock_timestamp();
  return new;
end $$;
drop trigger if exists tasks_touch on public.tasks;
create trigger tasks_touch before insert or update on public.tasks
  for each row execute function public.tasks_touch();

-- ---------- access: open to the website, limited to these three tables ----------
alter table public.list_items   enable row level security;
alter table public.app_settings enable row level security;
alter table public.tasks        enable row level security;

do $$
declare r record;
begin
  for r in select policyname, tablename from pg_policies
           where schemaname = 'public' and tablename in ('list_items', 'app_settings', 'tasks') loop
    execute format('drop policy %I on public.%I', r.policyname, r.tablename);
  end loop;
end $$;

revoke all on public.list_items, public.app_settings, public.tasks from anon, authenticated;
grant select, insert, update, delete on public.list_items, public.tasks to anon;
grant select on public.app_settings to anon;
grant update (report_date) on public.app_settings to anon;

create policy open_tasks    on public.tasks        for all    to anon using (true) with check (true);
create policy open_lists    on public.list_items   for all    to anon using (true) with check (true);
create policy open_set_read on public.app_settings for select to anon using (true);
create policy open_set_edit on public.app_settings for update to anon using (true) with check (true);

-- ---------- all-or-nothing replace ----------
-- Replaces tasks (and lists / report date when those keys are present).
-- Used by Import CSV, Restore, Load Sample, Clear All and their Undo.
create or replace function public.replace_all(p jsonb) returns void
language plpgsql security invoker set search_path = '' as $$
declare
  v_kind text;
begin
  if p ? 'tasks' then
    delete from public.tasks where id is not null;
    insert into public.tasks
      (id, task, assigned_date, assigned_by, job_function, due_date, completion_date,
       assigned_to_1, assigned_to_2, assigned_to_3, priority, pct, remarks, created_at)
    select coalesce(nullif(x->>'id', ''), gen_random_uuid()::text),
           x->>'task',
           nullif(x->>'ad', '')::date,
           coalesce(x->>'by', ''), coalesce(x->>'fn', ''),
           nullif(x->>'due', '')::date, nullif(x->>'cd', '')::date,
           coalesce(x->>'a1', ''), coalesce(x->>'a2', ''), coalesce(x->>'a3', ''),
           coalesce(x->>'pr', ''),
           coalesce(nullif(x->>'pct', '')::numeric, 0)::int,
           coalesce(x->>'rem', ''),
           coalesce(nullif(x->>'created', '')::timestamptz, now())
    from jsonb_array_elements(p->'tasks') with ordinality as e(x, n)
    order by n;
  end if;

  foreach v_kind in array array['members', 'assigners', 'functions'] loop
    if p ? v_kind then
      delete from public.list_items where kind = v_kind;
      insert into public.list_items (kind, name)
      select v_kind, btrim(x)
      from jsonb_array_elements_text(p->v_kind) with ordinality as e(x, n)
      where btrim(x) <> ''
      order by n
      on conflict do nothing;
    end if;
  end loop;

  if p ? 'reportDate' then
    update public.app_settings set report_date = nullif(p->>'reportDate', '')::date where id = 1;
  end if;
end $$;

revoke all on function public.replace_all(jsonb) from public, authenticated;
grant execute on function public.replace_all(jsonb) to anon;

commit;

notify pgrst, 'reload schema';
